# Franjas de precio de los hospedajes, calculadas con el promedio del rango en
# soles: permiten filtrar la oferta sin depender de rangos exactos.
FRANJAS_ALOJAMIENTO = (
    ("económico", "promedio hasta S/ 60 por noche"),
    ("medio", "promedio de S/ 61 a 150 por noche"),
    ("alto", "promedio de S/ 151 a 300 por noche"),
    ("premium", "promedio de más de S/ 300 por noche"),
)


def franja_de(rango):
    """Clasifica un rango 'S/ 40 - 90' usando el promedio de sus extremos."""
    extremos = [int(p) for p in str(rango or "").replace("S/", " ").replace("-", " ").split() if p.isdigit()]
    if not extremos:
        return None
    promedio = (extremos[0] + extremos[-1]) / 2
    if promedio <= 60:
        return "económico"
    if promedio <= 150:
        return "medio"
    if promedio <= 300:
        return "alto"
    return "premium"


