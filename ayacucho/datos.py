def puntos_del_mapa_centro():
    """Puntos del mapa con GPS propio, en el orden en que se numeran.

    Solo entran los que tienen coordenada publicada: las iglesias sin dato
    caerían todas sobre la plaza y darían una ubicación falsa.
    """
    por_nombre = {entrada["nombre"]: entrada for entrada in ATRACCIONES}
    por_nombre.update({entrada["nombre"]: entrada for entrada in IGLESIAS})
    return [
        por_nombre[nombre]
        for nombre in MAPA_CENTRO
        if nombre in por_nombre and "lat" in por_nombre[nombre]
    ]


