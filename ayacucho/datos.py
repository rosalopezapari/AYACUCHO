def todos_los_lugares():
    """Índice unificado de los lugares visitables, con sección y GPS resuelto."""
    lugares = []

    def agregar(entrada, seccion, provincia=None):
        salida = _entrada_con_gps(entrada, provincia or entrada.get("provincia", ""))
        salida["seccion"] = seccion
        lugares.append(salida)

    for atraccion in ATRACCIONES:
        agregar(atraccion, "Atracciones")
    nombres = {lugar["nombre"] for lugar in lugares}
    for iglesia in IGLESIAS:
        if iglesia["nombre"] not in nombres:
            agregar(iglesia, "Iglesias")
    for festividad in FESTIVIDADES:
        agregar(festividad, "Festividades")
    for artesania in ARTESANIAS:
        agregar(artesania, "Artesanias")
    for evento in EVENTOS_CULTURALES:
        agregar(evento, "Eventos Culturales")
    for option in todos_alojamientos():
        agregar(option, "Hospedajes")
    for opcion in todos_restaurantes():
        agregar(opcion, "Restaurantes")
    for comercio in todos_comercios():
        agregar(comercio, "Comercios")
    return lugares


