def gps_de(entrada):
    """Devuelve (lat, lng) de la entrada o de su ciudad; None si no hay referencia."""
    if "lat" in entrada and "lng" in entrada:
        return entrada["lat"], entrada["lng"]
    ciudad = str(entrada.get("ciudad", "")).strip()
    if ciudad in GPS_CIUDADES:
        return GPS_CIUDADES[ciudad]
    for nombre, coord in GPS_CIUDADES.items():
        if nombre.lower() in ciudad.lower():
            return coord
    return None


