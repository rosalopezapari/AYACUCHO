def _entrada_con_gps(entrada, provincia, extra=None):
    """Copia la entrada agregando 'provincia' y el GPS resuelto (propio o por ciudad)."""
    salida = dict(entrada)
    salida["provincia"] = provincia
    if extra:
        salida.update(extra)
    coord = gps_de(salida)
    if coord:
        salida["lat"], salida["lng"] = coord
    return salida


